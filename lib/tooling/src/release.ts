import { z } from "zod";

const FIRST = 0;
const TAG_PREFIX_LENGTH = 1;
const MINIMUM_ITEMS = 1;

export const platforms = ["darwin-arm64", "darwin-x64", "linux-arm64", "linux-x64"] as const;
export const platformSchema = z.enum(platforms);
export const versionSchema = z.string().regex(/^(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)$/u);
export const repositorySchema = z.string().regex(/^[\w.-]+\/[\w.-]+$/u);
export const artifacts = {
	beeswax: ["beeswax"],
	honeycomb: ["honeycomb"],
	colony: ["bee", "colony", "colony-runtime", "colony-worker", "colony-watchdog"],
	busybee: ["busybee"],
	qlock: ["qlock"],
	"hive-ui": ["hive-ui"],
};
export const executables = Object.values(artifacts).flat();
const archiveSchema = z.object({
	platform: platformSchema,
	file: z.string().regex(/^hive-[\d.]+-(?:darwin|linux)-(?:arm64|x64)\.tar\.gz$/u),
	sha256: z.string().regex(/^[a-f\d]{64}$/u),
});
export const releaseManifestSchema = z.object({
	version: versionSchema,
	revision: z.string().regex(/^[a-f\d]{40}$/u),
	bunVersion: z.string().min(MINIMUM_ITEMS),
	archives: z.array(archiveSchema).min(MINIMUM_ITEMS),
});

export type Platform = z.infer<typeof platformSchema>;
export type ReleaseManifest = z.infer<typeof releaseManifestSchema>;
export interface PackageHistory {
	/** Repository-relative directory; dot names the root package. */
	directory: string;
	/** Package name from its manifest. */
	name: string;
	/** Current package version, before the suite bump. */
	version: string;
	/** Git's abbreviated commit ID and subject, newest first. */
	commits: string[];
}

/** Choose the newest stable suite tag reachable from the release source. */
export function previousRelease(tags: string[]): string | undefined {
	return tags
		.filter(
			(tag) => tag.startsWith("v") && versionSchema.safeParse(tag.slice(TAG_PREFIX_LENGTH)).success,
		)
		.toSorted((left, right) =>
			Bun.semver.order(right.slice(TAG_PREFIX_LENGTH), left.slice(TAG_PREFIX_LENGTH)),
		)[FIRST];
}

/** Refuse duplicate/downgrade releases before changing any files. */
export function checkNextVersion(
	next: string,
	packages: PackageHistory[],
	previous: string | undefined,
): void {
	const current = packages.map((pkg) => pkg.version);
	if (previous !== undefined) {
		current.push(previous.slice(TAG_PREFIX_LENGTH));
	}
	if (current.some((version) => Bun.semver.order(next, version) <= FIRST)) {
		throw new Error(
			`Next suite version ${next} must exceed every package and previous release version.`,
		);
	}
}

/** Every package gets an entry, including packages with no commits in this release. */
export function releaseNotes(
	version: string,
	previous: string | undefined,
	packages: PackageHistory[],
): string {
	let range = "Initial release; all Git history.";
	if (previous !== undefined) {
		range = `Changes since ${previous}.`;
	}
	const sections = packages.map((pkg) => {
		let changes = "No change.";
		if (pkg.commits.length > FIRST) {
			changes = pkg.commits.map((commit) => `- ${commit}`).join("\n");
		}
		return `## ${pkg.name}\n\n${changes}`;
	});
	return `# Hive ${version}\n\n${range}\n\n${sections.join("\n\n")}\n`;
}

export function archiveName(version: string, platform: Platform): string {
	return `hive-${version}-${platform}.tar.gz`;
}

/** Render only complete releases: a formula cannot advertise an absent platform. */
export function homebrewFormula(manifest: ReleaseManifest, repository: string): string {
	if (
		manifest.archives.length !== platforms.length ||
		new Set(manifest.archives.map((archive) => archive.platform)).size !== platforms.length
	) {
		throw new Error("A Homebrew formula requires exactly one archive for each supported platform.");
	}
	const sources = ["darwin", "linux"].map((os) => {
		let system = "linux";
		if (os === "darwin") {
			system = "macos";
		}
		const arches = platforms
			.filter((platform) => platform.startsWith(os))
			.map((platform) => formulaSource(manifest, repository, platform));
		return `  on_${system} do\n${arches.join("\n\n")}\n  end`;
	});
	return formulaBody(sources);
}

// --- Private functions ---

function formulaSource(manifest: ReleaseManifest, repository: string, platform: Platform): string {
	const archive = manifest.archives.find((entry) => entry.platform === platform)!;
	if (archive.file !== archiveName(manifest.version, platform)) {
		throw new Error(`Archive filename does not match release identity: ${archive.file}`);
	}
	let cpu = "intel";
	if (platform.endsWith("arm64")) {
		cpu = "arm";
	}
	return (
		`    on_${cpu} do\n` +
		`      url "https://github.com/${repository}/releases/download/v${manifest.version}/${archive.file}"\n` +
		`      sha256 "${archive.sha256}"\n    end`
	);
}

function formulaBody(sources: string[]): string {
	return `# typed: false
# frozen_string_literal: true

# Generated by bun run release formula from verified release artifacts.
class Hive < Formula
  desc "Coding agent tools: worktrees, workflows, workers and a local work board"
  homepage "https://github.com/codethread/hive"

  depends_on "dicklesworthstone/tap/br"
  depends_on "dicklesworthstone/tap/bv"
  depends_on "git"

${sources.join("\n\n")}

  def install
    bin.install ${executables.map((name) => `"bin/${name}"`).join(",\n                ")}
    pkgshare.install "release.json"
  end

  test do
    ${executables.map((name) => versionTest(name)).join("\n    ")}
    system bin/"honeycomb", "--help"
    system bin/"busybee", "--help"
    system bin/"qlock", "status", "--lock", testpath/"queue.lock", "--json"
    refute_path_exists testpath/".beads"
  end
end
`;
}

function versionTest(name: string): string {
	return `assert_equal version.to_s, shell_output("#{bin}/${name} --version").strip`;
}
